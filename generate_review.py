# ============================================================

def build_data_section():
    lines = []
    lines.append(f"# 网易云音乐个人数据（导出时间：{datetime.now().strftime('%Y-%m-%d %H:%M')}）\n")

    rows = read_csv_rows(LIKED_CSV)
    if len(rows) > 1:
        lines.append(f"## 一、喜欢的音乐（共 {len(rows) - 1} 首）\n")
        lines.append("格式：歌曲名 | 音乐人 | 专辑\n")
        for r in rows[1:]:
            if len(r) >= 3:
                lines.append(f"{r[0]} | {r[1]} | {r[2]}")
        lines.append("")

    rows = read_csv_rows(ALBUM_CSV)
    if len(rows) > 1:
        lines.append(f"## 二、收藏的专辑（共 {len(rows) - 1} 张）\n")
        lines.append("格式：专辑名 | 音乐人\n")
        for r in rows[1:]:
            if len(r) >= 2:
                lines.append(f"{r[0]} | {r[1]}")
        lines.append("")

    rows = read_csv_rows(CREATED_CSV)
    if len(rows) > 1:
        grouped = {}
        for r in rows[1:]:
            if len(r) >= 4:
                pl_name = r[0]
                grouped.setdefault(pl_name, []).append((r[1], r[2], r[3]))
        lines.append(f"## 三、我创建的歌单（共 {len(grouped)} 个）\n")
        for pl_name, tracks in grouped.items():
            lines.append(f"### {pl_name}（{len(tracks)} 首）")
            for name, artist, album in tracks:
                lines.append(f"- {name} | {artist} | {album}")
            lines.append("")

    rows = read_csv_rows(SUBSCRIBED_CSV)
    if len(rows) > 1:
        grouped = {}
        for r in rows[1:]:
            if len(r) >= 4:
                pl_name = r[0]
                grouped.setdefault(pl_name, []).append((r[1], r[2], r[3]))
        lines.append(f"## 四、我收藏的歌单（共 {len(grouped)} 个）\n")
        for pl_name, tracks in grouped.items():
            lines.append(f"### {pl_name}（{len(tracks)} 首）")
            for name, artist, album in tracks:
                lines.append(f"- {name} | {artist} | {album}")
            lines.append("")

    return "\n".join(lines)


